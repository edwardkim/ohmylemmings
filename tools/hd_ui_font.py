#!/usr/bin/env python3
"""Verify the shipped font offline; --generate authors it with host FreeType.

No font library or system font lookup is used by Native/WASM at runtime.
"""
import argparse,hashlib,json,shlex,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
REV='ffebf8c1ee449e544955a7e813c54f9b73848eac'
URL=f'https://raw.githubusercontent.com/notofonts/noto-fonts/{REV}/hinted/ttf/NotoSans/NotoSans-SemiBold.ttf'
SOURCE=dict(url=URL,size=572924,sha256='87a8b90ece1e89746b544e4e086f85a3710e41485a8078f9be874837dfad45d5')
ALPHA='crates/lemmings-game/src/hd/ui_font.alpha'
METRICS='crates/lemmings-game/src/hd/ui_font_metrics.rs'
MANIFEST='assets/manifests/hd_ui_font.json'
def pin(root,name):
    b=(root/name).read_bytes();return dict(path=name,bytes=len(b),sha256=hashlib.sha256(b).hexdigest())
def save(p,m):p.write_text(json.dumps(m,indent=2)+'\n')
def verify(root=ROOT):
    m=json.loads((root/MANIFEST).read_text())
    for row in m['outputs']+[m['license']]:
        if pin(root,row['path'])!=row:raise ValueError('font material changed: '+row['path'])
    b=(root/ALPHA).read_bytes();w,h=m['width'],m['height'];rows=m['glyphs']
    if (w,h,len(b),len(rows))!=(1024,384,1024*384,95):raise ValueError('font dimensions/coverage')
    nonempty=0
    for n,(x,y,gw,gh,left,top,advance) in enumerate(rows):
        if not (x==n%16*64+2 and y==n//16*64+2 and 0<=gw<=60 and 0<=gh<=60 and -8<=left<=16 and -16<=top<=60 and 0<advance<=4096):raise ValueError('font glyph bounds')
        samples=[b[(y+j)*w+x+i] for j in range(gh) for i in range(gw)]
        if n==0:
            if samples:raise ValueError('space must be blank')
        elif not any(samples):raise ValueError('empty glyph')
        else:nonempty+=1
        for j in range(64):
            for i in range(64):
                if not (2<=i<gw+2 and 2<=j<gh+2) and b[((n//16)*64+j)*w+n%16*64+i]:raise ValueError('font gutter')
    return dict(status='PASS',glyphs=95,nonempty_glyphs=nonempty,partial_alpha=any(0<v<255 for v in b),runtime_rgba_bytes=w*h*4*3)
def generate(root=ROOT):
    local=root/'assets/local/hd-font';local.mkdir(parents=True,exist_ok=True);source=local/'NotoSans-SemiBold.ttf'
    if not source.exists():raise ValueError('fetch pinned font first with --fetch')
    if len(source.read_bytes())!=SOURCE['size'] or hashlib.sha256(source.read_bytes()).hexdigest()!=SOURCE['sha256']:raise ValueError('font source pin')
    flags=shlex.split(subprocess.check_output(['pkg-config','--cflags','--libs','freetype2'],text=True))
    binary=local/'font-raster';subprocess.run(['cc','-std=c99','-O2','-Wall','-Wextra','-Werror',str(root/'tools/font_raster.c'),'-o',str(binary),*flags],check=True)
    result=json.loads(subprocess.check_output([str(binary),str(source),str(root/ALPHA)],text=True))
    lines=['// Generated by tools/hd_ui_font.py; see assets/manifests/hd_ui_font.json.','pub(super) const GLYPHS: [[i32; 7]; 95] = [']
    lines += ['    ['+', '.join(map(str,row))+'],' for row in result['glyphs']];lines+= ['];','']
    (root/METRICS).write_text('\n'.join(lines))
    result.update(schema_version=1,issue='https://github.com/edwardkim/ohmylemmings/issues/184',source=SOURCE,revision=REV,license=pin(root,'third_party/NotoSans-OFL.txt'),outputs=[pin(root,ALPHA),pin(root,METRICS)],generator='tools/font_raster.c; FreeType FT_LOAD_RENDER | FT_LOAD_NO_HINTING | FT_LOAD_NO_AUTOHINT; 48px; grayscale coverage; no runtime font dependency',baseline=40,palettes=3,policy='Printable ASCII32..126. Source TTF unchanged and acquired under assets/local. Generated alpha is covered by upstream OFL; metadata/renderer are project code. Native/Web share exact glyph coverage; no OS font substitution. Unsupported characters display question mark. UI-only, no simulation change.')
    save(root/MANIFEST,result);return verify(root)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--fetch',action='store_true');p.add_argument('--generate',action='store_true');a=p.parse_args()
    if a.fetch:
        from reference_assets import download_bytes,checked_bytes
        data=download_bytes(SOURCE['url'],SOURCE['size']);checked_bytes(data,SOURCE,'HD UI font');target=ROOT/'assets/local/hd-font/NotoSans-SemiBold.ttf';target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
    print(json.dumps(generate() if a.generate else verify()))
if __name__=='__main__':main()
